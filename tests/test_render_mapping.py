# --- every sample (synthetic builds: one marked region per step) ----------------------------------------

def synthetic_build(objective: dict) -> tuple[str, str]:
    """(file name, text) of a build with one marked region per step of `objective`, in its language."""
    steps = [step["id"] for step in objective["steps"]]
    if objective["language"] == "python":
        body = "".join(f"    # step {step}\n    value_{step} = 1\n\n" for step in steps)
        return "build.py", f"def main(session, src, tgt):\n{body}    return 'OK'\n"
    return "build.sql", "".join(f"-- step {step}\nCREATE OR REPLACE TEMPORARY TABLE t_{step} AS SELECT 1 AS X;\n\n"
                                for step in steps)


@pytest.mark.parametrize("wf_id", [wf for wf in WORKFLOWS if wf != "wf_0005"])   # wf_0005 is tier T3: no build
def test_every_sample_renders_a_lint_clean_diagram_and_a_table_of_every_tool(tmp_path, wf_id):
    objective = _objective(wf_id)
    name, text = synthetic_build(objective)
    repo = make_repo(tmp_path, wf_id, text, build_name=name)

    assert run(repo, wf_id) == 0

    rendered = mapping(repo, wf_id)
    (block,) = mermaid_blocks(rendered)
    assert lint_mermaid(block) == []
    rows = table_rows(rendered)
    assert [row[0] for row in rows] == sorted_tool_labels(wf_id)
    in_a_step = {tool for step in objective["steps"] for tool in step["tools"]}
    for row in rows:
        if row[0][1:] in in_a_step:
            assert re.fullmatch(r"s\d+(, s\d+)*", row[3]) and re.fullmatch(r"\d+(–\d+)?(, \d+(–\d+)?)*", row[4])
        else:
            assert row[3].startswith("no effect: ") and row[4] == "—"
    for step in objective["steps"]:
        assert f'{step["id"]}["{step["id"]} · ' in block                        # every step is a node
    assert block.count("-.->") == len(objective["steps"])                     # one region per step


