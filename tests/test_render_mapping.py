#: What a translator writes for wf_0001, by hand (the canned one is Task A3's): three regions over five steps.
WF_0001_BUILD = """\
-- wf_0001 · Sales summary by region and size band
-- Written from objective.md; checked against golden data. {{src}} = source schema, {{tgt}} = target schema.
ALTER SESSION SET TIMEZONE = 'America/New_York', WEEK_START = 1;

-- step s1, s2
CREATE OR REPLACE TEMPORARY TABLE orders AS
SELECT LEFT(CUSTOMER, 10) AS CUSTOMER, STATUS AS ORDER_STATUS, ORDER_ID, REGION, AMOUNT_TXT, QTY, ORDER_DATE
FROM {{src}}.ORDERS;

-- step s3, s4
CREATE OR REPLACE TABLE {{tgt}}.SALES_SUMMARY AS
SELECT REGION, SIZE_BAND, SUM(NET) AS TOTAL_NET
FROM orders
WHERE REGION <> 'WEST'
GROUP BY REGION, SIZE_BAND
ORDER BY TOTAL_NET DESC, REGION;

-- step s5
CREATE OR REPLACE TABLE {{tgt}}.EXCLUDED_ORDERS AS
SELECT CUSTOMER, ORDER_STATUS, ORDER_ID, REGION, AMOUNT_TXT, QTY, ORDER_DATE
FROM orders
WHERE NOT (REGION <> 'WEST') OR REGION IS NULL;
"""

_FORMULA = ('AMOUNT:Double = ToNumber([AMOUNT_TXT]); NET:Double = Round([AMOUNT] * IIF([QTY] >= 10, 0.9, 1), 0.01); '
            'SIZE_BAND:V_String(10) = IF [AMOUNT] >= 1000 THEN "LARGE" ELSEIF [AMOUNT] >= 100 THEN "MEDIUM" '
            'ELSE "SMALL" ENDIF')
_SUMMARIZE = ('group by REGION, SIZE_BAND; Sum(NET) as TOTAL_NET; Count(ORDER_ID) as ORDERS; '
              'CountNonNull(AMOUNT) as PRICED_ORDERS; Max(ORDER_DATE) as LAST_ORDER')

#: The mapping the three-region build above must give. A cell longer than 120 characters is cut to 119 and
#: ends in an ellipsis; a step's tools are the digest's `T<id> <Type>` in id order; a shared region
#: (`-- step s1, s2`) is drawn once with a dotted edge from each of its steps.
WF_0001_MAPPING = f"""\
# wf_0001 — how the Alteryx workflow maps to build.sql

_Generated by `scripts/render_mapping.py` from `objective.json`, the `-- step` markers in `build.sql` and `parsed/dag.json`. Do not edit it: the line numbers are those of `build.sql` when it was rendered._

```mermaid
flowchart LR
  subgraph AX["Alteryx · sales_summary.yxmd"]
    s1["s1 · Read and clean orders<br/>T1 Input · T2 Select"]
    s2["s2 · Set the WEST region aside<br/>T3 Filter"]
    s3["s3 · Work out net value and size band<br/>T4 Formula"]
    s4["s4 · Total by region and size band<br/>T5 Summarize · T6 Sort · T7 Output"]
    s5["s5 · List the excluded orders<br/>T8 Output"]
  end
  subgraph CODE["build.sql"]
    r1["lines 6–8 · TEMPORARY TABLE orders"]
    r2["lines 11–16 · CREATE TABLE SALES_SUMMARY"]
    r3["lines 19–22 · CREATE TABLE EXCLUDED_ORDERS"]
  end
  s1 --> s2
  s2 --> s3
  s2 --> s5
  s3 --> s4
  s1 -.-> r1
  s2 -.-> r1
  s3 -.-> r2
  s4 -.-> r2
  s5 -.-> r3
```

| tool | type | what it does | step | lines |
|---|---|---|---|---|
| T1 | Input | `read orders.yxdb (yxdb)` | s1 | 6–8 |
| T2 | Select | `CUSTOMER:String(10); STATUS → ORDER_STATUS; other fields kept` | s1 | 6–8 |
| T3 | Filter | `[REGION] != "WEST"` | s2 | 6–8 |
| T4 | Formula | `{_FORMULA[:119]}…` | s3 | 11–16 |
| T5 | Summarize | `{_SUMMARIZE[:119]}…` | s4 | 11–16 |
| T6 | Sort | `TOTAL_NET desc, REGION asc` | s4 | 11–16 |
| T7 | Output | `write sales_summary.yxdb (yxdb), mode overwrite` | s4 | 11–16 |
| T8 | Output | `write excluded_orders.csv (csv), mode overwrite` | s5 | 19–22 |
"""


def _sample_dag(wf_id: str) -> dict:
    """The sample's `parsed/dag.json` as `parse.py` builds it from the `.yxmd` (cached; nothing edits it)."""
    if wf_id not in _DAGS:
        source = next((SAMPLES / wf_id / "source").glob("*.yxmd"))
        _DAGS[wf_id], _ = parse.parse_file(source)
    return copy.deepcopy(_DAGS[wf_id])


def _objective(wf_id: str) -> dict:
    return read_json(SAMPLES / wf_id / "canned" / "objective.json")


def make_repo(tmp_path: Path, wf_id: str = WF, build: str | None = WF_0001_BUILD, *, build_name: str = "build.sql",
              objective: dict | None = None, dag: dict | None = None) -> Repo:
    """A repo holding `wf_id` as the translate stage leaves it: the parsed dag, the canned objective, one build file."""
    repo = Repo(tmp_path)
    write_json(repo.wf(wf_id, "parsed", "dag.json"), dag if dag is not None else _sample_dag(wf_id))
    write_json(repo.wf(wf_id, "objective.json"), objective if objective is not None else _objective(wf_id))
    if build is not None:
        write_text(repo.wf(wf_id, build_name), build)
    return repo


def run(repo: Repo, wf_id: str = WF) -> int:
    return render_mapping.main([wf_id, "--root", str(repo.root)])


def mapping(repo: Repo, wf_id: str = WF) -> str:
    return repo.wf(wf_id, "docs", "mapping.md").read_text(encoding="utf-8")


def table_rows(text: str) -> list[list[str]]:
    """The cells of each body row of the tool table, split on the pipes that are not escaped."""
    return [[cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
            for line in text.splitlines() if line.startswith("| T")]


def sorted_tool_labels(wf_id: str) -> list[str]:
    return [f"T{tool}" for tool in sorted(dag_tool_ids(_sample_dag(wf_id)), key=tool_key)]


