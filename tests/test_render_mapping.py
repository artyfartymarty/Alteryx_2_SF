def test_a_step_in_two_regions_lists_both_ranges_and_has_an_edge_to_each(tmp_path):
    build = """\
-- step s1, s2
CREATE OR REPLACE TEMPORARY TABLE orders AS SELECT 1 AS X FROM {{src}}.ORDERS;

-- step s3
CREATE OR REPLACE TABLE {{tgt}}.SALES_SUMMARY AS SELECT 1 AS X FROM orders;

-- step s4
CREATE OR REPLACE TABLE {{tgt}}.EXCLUDED_ORDERS AS
SELECT 1 AS X FROM orders;

-- step s5, s4
INSERT INTO {{tgt}}.EXCLUDED_ORDERS SELECT 2 FROM orders;
"""
    repo = make_repo(tmp_path, build=build)
    assert run(repo) == 0
    text = mapping(repo)

    assert 'r1["line 2 · TEMPORARY TABLE orders"]' in text        # a one-line region says "line", not "lines"
    assert 'r3["lines 8–9 · CREATE TABLE EXCLUDED_ORDERS"]' in text
    assert 'r4["line 12 · INSERT INTO EXCLUDED_ORDERS"]' in text
    assert "  s4 -.-> r3\n  s4 -.-> r4\n  s5 -.-> r4\n" in text
    rows = {row[0]: row for row in table_rows(text)}
    assert (rows["T5"][3], rows["T5"][4]) == ("s4", "8–9, 12")        # step s4's two regions, in file order
    assert (rows["T1"][3], rows["T1"][4]) == ("s1", "2")
    assert (rows["T8"][3], rows["T8"][4]) == ("s5", "12")


