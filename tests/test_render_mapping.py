def test_names_and_expressions_with_markup_characters_stay_inside_their_cell_and_label(tmp_path):
    objective = _objective(WF)
    objective["steps"][0]["name"] = 'Read "orders" [raw] (all) {x}; #1 <b>bold</b> | pipe\nline two'
    objective["steps"][1]["name"] = "IIF([QTY]>=10,(1"
    dag = _sample_dag(WF)
    next(n for n in dag["nodes"] if n["tool_id"] == "3")["config"]["expression"] = '[A] = "x|y" OR [B] < `5`'
    repo = make_repo(tmp_path, objective=objective, dag=dag)

    assert run(repo) == 0
    text = mapping(repo)

    (block,) = mermaid_blocks(text)
    assert lint_mermaid(block) == []
    assert ('s1["s1 · Read #quot;orders#quot; #91;raw#93; #40;all#41; #123;x#125;#59; #35;1 '
            '#lt;b#gt;bold#lt;/b#gt; | pipe line two<br/>T1 Input · T2 Select"]') in block
    assert 's2["s2 · IIF#40;#91;QTY#93;#gt;=10,#40;1<br/>T3 Filter"]' in block
    rows = {row[0]: row for row in table_rows(text)}
    assert all(len(row) == 5 for row in rows.values())               # the pipe in the expression is escaped
    assert rows["T3"][2] == '`` [A] = "x\\|y" OR [B] < `5` ``'         # a backtick in it gets a longer fence


