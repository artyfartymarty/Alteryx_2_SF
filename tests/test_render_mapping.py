# --- the command line ------------------------------------------------------------------------------------

def _cli(*arguments: str):
    return subprocess.run([sys.executable, str(ROOT / "scripts" / "render_mapping.py"), *arguments],
                          capture_output=True, text=True, encoding="utf-8", cwd=ROOT)


def test_the_script_runs_from_the_command_line_with_the_exit_codes_it_documents(tmp_path):
    repo = make_repo(tmp_path)

    done = _cli(WF, "--root", str(repo.root))
    assert done.returncode == 0 and done.stdout.strip().endswith("mapping.md"), done.stderr
    assert mapping(repo) == WF_0001_MAPPING

    write_text(repo.wf(WF, "build.sql"), WF_0001_BUILD.replace("-- step s5\n", ""))
    done = _cli(WF, "--root", str(repo.root))
    assert done.returncode == 1 and "step s5 has no region in build.sql" in done.stderr

    assert _cli("wf_0009", "--root", str(repo.root)).returncode == 2
    assert _cli().returncode == 2                                  # argparse: no workflow id
